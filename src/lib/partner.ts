export type PartnerReading = {
  /** 对方日主（推断） */
  starGan: Gan;
  /** 对应十神 */
  starTenGod: ShiShen;
  /** 关系类型 */
  kind: string;
  look: string;
  vibe: string;
  style: string;
  risk: string;
  job: string[];
  scene: string;
  /** 这段关系的走向提示 */
  prospect: string;
  /** 关系里最该注意的一件事 */
  advice: string;
};

export function readPartner(
  pillars: FourPillars,
  gender: "female" | "male",
): PartnerReading {
  const dayGan = pillars.day.gan;
  const dayZhi = pillars.day.zhi;
  const hidden = ZHI_HIDDEN[dayZhi];
  const hiddenGods = hidden.map((g) => shiShen(dayGan, g));

  /**
   * 配偶星：女看官杀（克我），男看财（我克）。
   * 优先取日支藏干里的那一个——因为它就在夫妻宫。
   */
  const wanted: ShiShen[] =
    gender === "female" ? ["正官", "七杀"] : ["正财", "偏财"];

  let starGan: Gan | undefined;
  let starTenGod: ShiShen | undefined;

  for (let i = 0; i < hidden.length; i++) {
    if (wanted.includes(hiddenGods[i])) {
      starGan = hidden[i];
      starTenGod = hiddenGods[i];
      break;
    }
  }

  // 夫妻宫里没有配偶星 → 退一步，取全局里最强的那个（用日支本气代替）
  if (!starGan || !starTenGod) {
    starGan = hidden[0];
    starTenGod = hiddenGods[0];
  }

  const profile = TEN_GOD_PROFILE[starTenGod];
  const element = GAN_ELEMENT[starGan];

  // 夫妻宫与其它柱的地支是否相冲（冲则有分合节奏）
  const CHONG: Record<Zhi, Zhi> = {
    子: "午", 午: "子", 丑: "未", 未: "丑", 寅: "申", 申: "寅",
    卯: "酉", 酉: "卯", 辰: "戌", 戌: "辰", 巳: "亥", 亥: "巳",
  };
  const otherZhi = [pillars.year.zhi, pillars.month.zhi, pillars.hour?.zhi].filter(
    Boolean,
  ) as Zhi[];
  const clashWith = otherZhi.find((z) => CHONG[dayZhi] === z);
  const hasClash = Boolean(clashWith);

  const prospect = hasClash
    ? `你的日支（夫妻宫）与${clashWith}相冲，这段关系会有明显的分合节奏——不是一路顺，但也不是走不通。冲意味着"反复"：会分开，也会回来。`
    : dayZhi === "子" || dayZhi === "午" || dayZhi === "卯" || dayZhi === "酉"
      ? "日支坐桃花位，对方出现得快，但你也要留意——来得快的关系，考验通常在后面。"
      : "夫妻宫没有冲，这段关系不会大起大落，更像慢慢渗进来的那种。";

  return {
    starGan,
    starTenGod,
    kind: profile.vibe.split("：")[0],
    look: `${ELEMENT_LOOK[element]}\n\n${profile.look}`,
    vibe: profile.vibe,
    style: profile.style,
    risk: profile.risk,
    job: profile.job,
    scene: ZHI_SCENE[dayZhi],
    prospect,
    advice:
      gender === "female"
        ? `你的夫妻宫里透出${starGan}（${starTenGod}），说明你天然会被「${profile.vibe.split("：")[0]}」的人吸引。这类人一开始很对味，但真正能走下去的，是他愿意在你面前也示弱——而不是一直当那个靠得住的人。`
        : `你的夫妻宫里透出${starGan}（${starTenGod}），说明你容易对「${profile.vibe.split("：")[0]}」的人上心。这类关系里你要学的不是追，是让对方也觉得需要你——否则你会一直在付出那一侧。`,
  };
}

