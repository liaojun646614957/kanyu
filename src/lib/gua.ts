export function guaOf(lines: Line[]): {
  upper: number;
  lower: number;
  name: string;
  order: number;
  /** 便于展示：上卦名 + 下卦名 */
  full: string;
} {
  let lowerBin = 0;
  let upperBin = 0;
  lines.forEach((l, i) => {
    if (!l.yang) return;
    if (i < 3) lowerBin |= 1 << i;
    else upperBin |= 1 << (i - 3);
  });
  const upper = BIN_TO_XIAN[upperBin];
  const lower = BIN_TO_XIAN[lowerBin];
  const entry = GUA_TABLE[upper][lower];
  return {
    upper,
    lower,
    name: entry.name,
    order: entry.order,
    full: `${TRIGRAM[upper].nature}${TRIGRAM[lower].nature}`,
  };
}

