/**
 * 六十四卦 · 摇卦。
 *
 * 摇卦规则（传统三钱法）：
 *   三背（3×3=9）→ 老阳 ○，变爻
 *   两背一字（3+3+2=8）→ 少阴 - -
 *   一背二字（3+2+2=7）→ 少阳 —
 *   三字（2+2+2=6）→ 老阴 ✕，变爻
 * 概率：少阳 3/8、少阴 3/8、老阳 1/8、老阴 1/8
 */

export type LineKind = "老阴" | "少阳" | "少阴" | "老阳";

export type Line = {
  /** true = 阳爻（实线） */
  yang: boolean;
  /** true = 变爻 */
  changing: boolean;
  kind: LineKind;
  /** 三枚铜钱点数总和 6..9 */
  sum: number;
};

export function castLine(rand: () => number = Math.random): Line {
  let sum = 0;
  for (let i = 0; i < 3; i++) sum += rand() < 0.5 ? 2 : 3;
  const kind: LineKind = sum === 9 ? "老阳" : sum === 6 ? "老阴" : sum === 7 ? "少阳" : "少阴";
  return { yang: sum % 2 === 1, changing: sum === 6 || sum === 9, kind, sum };
}

